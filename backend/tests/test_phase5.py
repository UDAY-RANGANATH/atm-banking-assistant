"""
Phase 5 automated test suite - Intelligent Application Form Autofill.

Verification approach: this script can run in two modes.
  1. SERVICE mode  - direct service-layer tests (no server required)
  2. API mode      - HTTP tests against a running server (default port 8000)

Fixtures are SYNTHETIC documents generated by scripts/generate_test_docs.py.
No real identity documents are used anywhere in testing.

Print-safe on cp1252 consoles (ascii fallback for non-latin output).
"""

import sys
import json
import urllib.request
import urllib.error
from pathlib import Path

BACKEND = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(BACKEND))

FIXTURES = BACKEND / "tests" / "fixtures"
RESULTS = {"pass": 0, "fail": 0, "failures": []}


def report(name, ok, detail=""):
    if ok:
        RESULTS["pass"] += 1
        print_safe("PASS: " + name)
    else:
        RESULTS["fail"] += 1
        RESULTS["failures"].append(name)
        print_safe("FAIL: " + name + (" - " + str(detail) if detail else ""))


def print_safe(s):
    try:
        print(s)
    except Exception:
        print(s.encode("ascii", errors="replace").decode())


def api(method, path, body=None, base="http://127.0.0.1:8000"):
    """HTTP helper. Returns (status, parsed_json_or_None)."""
    url = base + path
    data = None
    headers = {}
    if body is not None:
        data, headers = json.dumps(body).encode(), {"Content-Type": "application/json"}
    req = urllib.request.Request(url, data=data, headers=headers, method=method)
    try:
        resp = urllib.request.urlopen(req, timeout=120)
        raw = resp.read()
        try:
            return resp.status, json.loads(raw.decode())
        except Exception:
            return resp.status, None
    except urllib.error.HTTPError as e:
        raw = e.read()
        try:
            return e.code, json.loads(raw.decode())
        except Exception:
            return e.code, None


