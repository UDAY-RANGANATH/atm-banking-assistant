    api("DELETE", f"/api/session/{te_session}")
    api("DELETE", f"/api/session/{hi_session}")

    # 59-service integration spot checks (reusable configurations)
    status, sess5 = api("POST", "/api/session?language=en", body={})
    spot = sess5["session_id"]
