def run_api_tests():
    print_safe("")
    print_safe("=== API TESTS (http://127.0.0.1:8000) - Phase 5 ===")

    status, body = api("GET", "/api/health")
    report("Health endpoint", status == 200)

    status, sess = api("POST", "/api/session?language=en", body={})
    report("Session created", status == 200 and "session_id" in sess, sess)
    session_id = sess["session_id"]

    # init application for savings account (Phase 5 <-> Phase 2/3 integration)
    status, init = api("POST", "/api/applications/init",
                       body={"session_id": session_id, "service_id": "acc-001"})
    report("Init application endpoint", status == 200 and init.get("application_id"), init)
    application_id = init.get("application_id", "")
    report("Form carries Phase 2 form number (prototype)", init.get("form_number") == "ACC-001")
    field_ids = [f["field_id"] for f in init.get("fields", [])]
    report("Savings account form shows only account-relevant fields",
           "applicant_name" in field_ids and "loan_amount" not in field_ids,
           field_ids)

    # upload + confirm a real synthetic PAN scan through Phase 4 pipeline
    status, _, _ = upload_scan(session_id, "acc-001", "doc-pan", "pan_en_DEMON0123F.png")
    report("PAN scan uploaded via Phase 4 scanner", status == 200, status)

    # autofill before confirmation - nothing eligible yet? (scan is
    # confirmation_pending -> not used; customer must confirm first)
    status, prefill = api("POST", f"/api/applications/{application_id}/autofill?session_id={session_id}")
    report(
        "Autofill before customer confirmation fills nothing",
        status == 200 and all(not f["source"] for f in prefill.get("fields", [])),
    )

    # fetch the last scan and confirm it (explicit customer confirmation)
    status, scans = api("GET", f"/api/scanner/status/{session_id}")
    last_scan = None
    for svc_state in (scans or {}).get("services", {}).values():
        for doc_info in svc_state.get("scan_status_by_document", {}).values():
            last_scan = doc_info["scan_id"]
    report("Scanner status exposes scan id for confirmation", bool(last_scan), scans)
    if last_scan:
        status, conf = api("POST", f"/api/scanner/confirm/{last_scan}", body={})
        report("Customer confirmation of scan", status == 200 and conf.get("status") == "confirmed")

    status, filled = api("POST", f"/api/applications/{application_id}/autofill?session_id={session_id}")
    report("Autofill endpoint runs", status == 200, filled)
    name_f = next((f for f in filled.get("fields", []) if f["field_id"] == "applicant_name"), {})
    report(
        "Applicant name auto-filled from confirmed PAN OCR",
        name_f.get("status") in ("AUTO_FILLED", "LOW_CONFIDENCE") and bool(name_f.get("value")),
        name_f,
    )
    pan_f = next((f for f in filled.get("fields", []) if f["field_id"] == "pan_number"), {})
    report(
        "PAN number is missing on savings form OR filled with masked value",
        pan_f.get("field_id") is None or ("XX" in (pan_f.get("value") or "") or pan_f.get("value") is None),
        pan_f,
    )

    # field-mappings introspection
    status, maps = api("GET", f"/api/applications/{application_id}/field-mappings?session_id={session_id}")
    report("Field-mappings endpoint exposes registry subset used by service",
           status == 200 and any(m["form_field"] == "applicant_name" for m in maps.get("mappings", [])))

    # manual edit on a missing field (customer completes what OCR could not)
    status, err = api("PATCH", f"/api/applications/{application_id}/fields/mobile_number",
                      body={"session_id": session_id, "action": "edit", "value": "123"})
    report("Service-level validation enforced via API (422 + i18n key)",
           status == 422 and str(err.get("detail", "")).startswith("pattern."), err)

    status, patched = api("PATCH", f"/api/applications/{application_id}/fields/mobile_number",
                          body={"session_id": session_id, "action": "edit", "value": "9876543210"})
    report("Manual edit via API marks CUSTOMER_EDITED",
           status == 200 and patched.get("record", {}).get("status") == "CUSTOMER_EDITED", patched)

    # confirm endpoint (explicit customer approval)
    status, confirmed = api("POST", f"/api/applications/{application_id}/fields/confirm",
                            body={"session_id": session_id,
                                  "field_ids": ["mobile_number", "applicant_name"]})
    report("Confirm endpoint marks fields CUSTOMER_CONFIRMED",
           status == 200 and set(confirmed.get("confirmed", [])) == {"mobile_number", "applicant_name"},
           confirmed)

    # accept + clear actions
    status, acc = api("PATCH", f"/api/applications/{application_id}/fields/date_of_birth",
                      body={"session_id": session_id, "action": "accept"})
    report("Accept Value action via API", status == 200 and acc.get("record", {}).get("status") == "CUSTOMER_CONFIRMED", acc)
    status, cleared = api("PATCH", f"/api/applications/{application_id}/fields/date_of_birth",
                          body={"session_id": session_id, "action": "clear"})
    report("Clear Value action via API -> MISSING",
           status == 200 and cleared.get("record", {}).get("status") == "MISSING", cleared)

    # save progress + reload via GET form (persistence)
    status, saved = api("POST", f"/api/applications/{application_id}/save?session_id={session_id}")
    report("Save endpoint persists draft (never submits)", status == 200 and saved.get("status") == "saved", saved)
    status, reloaded = api("GET", f"/api/applications/{application_id}/form?session_id={session_id}")
    re_f = {f["field_id"]: f for f in reloaded.get("fields", [])}
    report(
        "Progress persisted: edited/confirmed states survive reload",
        re_f.get("mobile_number", {}).get("status") == "CUSTOMER_CONFIRMED"
        and re_f.get("applicant_name", {}).get("status") == "CUSTOMER_CONFIRMED",
    )

    # completion status
    status, comp = api("GET", f"/api/applications/{application_id}/completion-status?session_id={session_id}")
    report("Completion status endpoint", status == 200 and "total_fields" in comp, comp)
    report("Completion status lists missing warnings", any(w["kind"] == "missing" for w in comp.get("warnings", [])))
    report(
        "Ready to continue only when no low-confidence/conflict remains",
        comp.get("ready_to_continue") in (True, False),
    )

    # ownership enforcement: second session cannot touch the application
    status, sess2 = api("POST", "/api/session?language=en", body={})
    other_session = sess2.get("session_id")
    status_other, resp_other = api("GET", f"/api/applications/{application_id}/form?session_id={other_session}")
    report("Cross-session access rejected", status_other in (403, 404), status_other)
