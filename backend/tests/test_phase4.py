def run_service_tests():
    print_safe("")
    print_safe("=== SERVICE LAYER TESTS ===")

    from app.services import image_processing as ip
    from app.services import ocr_engine
    from app.services import extraction as ex
    from app.services import scanner as sc
    from app.services.session import session_service
    from app.services.document_engine import (
        get_service_mappings, update_checklist_status,
        get_checklist_progress, DocumentRequirementStatus, SERVICE_DOCUMENT_MAPPINGS,
    )
    from app.services.banking_services import SERVICES, get_service
    import cv2
    import numpy as np

    # --- OCR engine ---
    report("OCR engine available", ocr_engine.AVAILABLE)
    report(
        "OCR languages eng/hin/tel present",
        all(l in ocr_engine.AVAILABLE_LANGUAGES for l in ["eng", "hin", "tel"]),
        ocr_engine.AVAILABLE_LANGUAGES,
    )
    svc = ocr_engine.get_ocr_service()

    pan = ip.load_image(str(FIXTURES / "pan_en_DEMON0123F.png"))

    # --- Preprocessing ---
    proc, info = ip.preprocess(pan, apply_threshold=False)
    report("Preprocessing produces output", proc is not None)
    proc_t, _ = ip.preprocess(pan, apply_threshold=True)
    report("Thresholded variant produces output", proc_t is not None)

    # --- Quality on good image ---
    q_good = ip.quality_summary(ip.assess_quality(proc))
    report("Good scan quality is GOOD/WARNING (not POOR)", q_good["status"] != "POOR", q_good)

    # --- Quality on blurry image ---
    blurry = cv2.GaussianBlur(pan, (41, 41), 30)
    q_blur = ip.quality_summary(ip.assess_quality(blurry))
    report("Blur detected on blurred image", "blurry" in q_blur["issues"], q_blur["issues"])

    # --- Quality on dark image ---
    dark = cv2.convertScaleAbs(pan, alpha=0.12, beta=0)
    q_dark = ip.quality_summary(ip.assess_quality(dark))
    report(
        "Darkness detected on dark image",
        any(i in q_dark["issues"] for i in ("underexposed", "poor_lighting")),
        q_dark["issues"],
    )

    # --- Quality on tiny image ---
    tiny = cv2.resize(pan, (150, 210))
    q_tiny = ip.quality_summary(ip.assess_quality(tiny))
    report("Low resolution detected on small image", q_tiny["status"] in ("POOR", "WARNING"), q_tiny["status"])

    # --- Quality on rotated image ---
    h, w = pan.shape[:2]
    m = cv2.getRotationMatrix2D((w // 2, h // 2), 30, 1.0)
    rotated = cv2.warpAffine(pan, m, (w, h), borderValue=(255, 255, 255))
    q_rot = ip.quality_summary(ip.assess_quality(rotated))
    report(
        "Rotation/cropping flagged on tilted image",
        "excessive_rotation" in q_rot["issues"] or "document_boundary_not_detected" in q_rot["issues"],
        q_rot["issues"],
    )

    # --- Perspective correction ---
    report(
        "Boundary/perspective info present on clean scan",
        info.get("boundary_detected") in (True, False) and info.get("processed_size") is not None,
    )

    # --- OCR: English PAN ---
    r_pan = svc.run(proc, ["eng", "hin", "tel"])
    report("OCR extracts text from PAN fixture", len(r_pan["text"].strip()) > 10)
    report("OCR confidence is real (>50 on clean synthetic PAN)", r_pan["confidence"] > 50, r_pan["confidence"])
    report("OCR reports languages used", r_pan["languages_used"] == ["eng", "hin", "tel"])

    # --- Classification ---
    cls = ex.classify_document(r_pan["text"], "doc-pan")
    report("PAN classified MATCH", cls["match"] == "MATCH", cls)
    cls_bad = ex.classify_document(r_pan["text"], "doc-salary-slips")
    report("PAN text vs salary-slip expectation = MISMATCH", cls_bad["match"] == "MISMATCH", cls_bad["match"])
    cls_unknown = ex.classify_document("some random words", "doc-pan")
    report("Random text = UNKNOWN classification", cls_unknown["match"] == "UNKNOWN", cls_unknown["match"])

    # --- Extraction schemas present for all mapped doc types ---
    mapped_types = set()
    for mapping in SERVICE_DOCUMENT_MAPPINGS:
        t = ex.DOC_TYPE_BY_DOCUMENT_ID.get(mapping.document_id)
        if t:
            mapped_types.add(t)
    missing = [t for t in mapped_types if t not in ex.EXTRACTION_SCHEMAS]
    report("Extraction schema exists for every mapped doc type", not missing, missing)

    # --- English extraction: PAN ---
    res_pan = ex.process_scan_result(r_pan, "doc-pan")
    report("PAN extraction SUCCESS", res_pan["extraction_status"] == "SUCCESS", res_pan["extraction_status"])
    f = res_pan["fields"]
    report("PAN name extracted", f["full_name"]["value"] is not None, f["full_name"])
    report("PAN DOB extracted", f["date_of_birth"]["value"] == "15/01/2005", f["date_of_birth"]["value"])
    report(
        "PAN identifier extracted and masked",
        f["document_identifier"]["value"] is not None
        and ("X" in f["document_identifier"]["value"] or "*" in f["document_identifier"]["value"]),
        f["document_identifier"]["value"],
    )
    report(
        "Null preservation (fathers name absent = null, not invented)",
        f["fathers_name"]["value"] is None,
        f["fathers_name"]["value"],
    )

    # --- Extraction: Aadhaar Hindi (Devanagari) ---
    aad_hi = ip.load_image(str(FIXTURES / "aadhaar_hi_2345_1234_5678.png"))
    proc_hi, _ = ip.preprocess(aad_hi, apply_threshold=False)
    r_hi = svc.run(proc_hi, ["eng", "hin", "tel"])
    res_hi = ex.process_scan_result(r_hi, "doc-aadhaar-address")
    hi_fields = res_hi["fields"]
    report(
        "Hindi aadhaar: DOB + masked identifier extracted (script-neutral fields)",
        hi_fields["date_of_birth"]["value"] is not None and hi_fields["document_identifier"]["value"] is not None,
    )
    report(
        "No translation of extracted values (raw preserved)",
        hi_fields["date_of_birth"]["value"].count("/") == 2,
    )

    # --- Extraction: Telugu marksheet ---
    mk_te = ip.load_image(str(FIXTURES / "marksheet_te_Demo_Anjali_2022.png"))
    proc_te, _ = ip.preprocess(mk_te, apply_threshold=False)
    r_te = svc.run(proc_te, ["eng", "hin", "tel"])
    res_te = ex.process_scan_result(r_te, "doc-12th-marksheet")
    report(
        "Telugu marksheet: student name preserved",
        res_te["fields"]["student_name"]["value"] is not None,
    )

    # --- Empty OCR result ---
    empty_img = 255 * np.ones((300, 400), dtype=np.uint8)  # single-channel blank
    r_blank = svc.run(cv2.cvtColor(empty_img, cv2.COLOR_GRAY2BGR), ["eng"])
    res_blank = ex.process_scan_result(r_blank, "doc-salary-slips")
    report(
        "Empty OCR produces EMPTY_OCR status and null fields",
        res_blank["extraction_status"] == "EMPTY_OCR"
        and all(v["value"] is None for v in res_blank["fields"].values()),
        res_blank["extraction_status"],
    )

    # --- Mismatched document does not silently pass ---
    res_mismatch = ex.process_scan_result(r_pan, "doc-passport")
    report(
        "Mismatch warning raised for wrong expected type",
        res_mismatch["classification"]["match"] == "MISMATCH",
        res_mismatch["classification"]["match"],
    )

    # --- Scanner: association validation ---
    try:
        sc.validate_application_document("sess-x", "acc-001", "doc-fee-structure")
        report("Invalid association rejected", False, "accepted fee-structure for savings")
    except ValueError:
        report("Invalid association rejected", True)
    try:
        sc.validate_application_document("", "", "doc-not-real")
        report("Unknown document rejected", False)
    except ValueError:
        report("Unknown document rejected", True)
    try:
        sc.validate_application_document("", "acc-999", "doc-pan")
        report("Unknown service rejected", False)
    except ValueError:
        report("Unknown service rejected", True)

    # --- Status transitions ---
    valid_pairs = [
        ("uploaded", "ocr_processing"), ("ocr_processing", "readable"),
        ("readable", "confirmed"), ("confirmed", "needs_rescan"),
        ("needs_rescan", "uploaded"),
    ]
    report("Valid status transitions defined", all(b in sc.VALID_TRANSITIONS[a] for a, b in valid_pairs))
    report(
        "Invalid transition rejected (pending -> confirmed)",
        "confirmed" not in sc.VALID_TRANSITIONS.get("pending", set()),
    )

    # --- Mandatory docs never forced to Not Applicable ---
    report(
        "sync_checklist_status never maps to NOT_APPLICABLE",
        sc.DocumentRequirementStatus.NOT_APPLICABLE not in
        [sc.DocumentRequirementStatus.UPLOADED, sc.DocumentRequirementStatus.READABLE,
         sc.DocumentRequirementStatus.NEEDS_RESCAN],
    )
    return True


