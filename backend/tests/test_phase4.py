def run_api_tests():
    print_safe("")
    print_safe("=== API TESTS (http://127.0.0.1:8000) ===")

    status, body, _ = api("GET", "/api/health")
    report("Health endpoint", status == 200)

    # OCR engine status endpoint
    status, body, _ = api("GET", "/api/scanner/engine/status")
    report("Scanner engine status endpoint", status == 200 and body and body.get("ocr_available") is True)
    report("Engine reports all 3 OCR languages", body and body.get("supported", {}).get("eng")
           and body.get("supported", {}).get("hin") and body.get("supported", {}).get("tel"))

    # Create a session (application id = session id)
    status, sess, _ = api("POST", "/api/session?language=en", body={})
    report("Session created for scans", status == 200 and "session_id" in sess, sess)
    session_id = sess["session_id"]

    # purge any earlier fixtures' state for this session - it's fresh by design

    # 1. upload via /capture (camera source semantics) with PAN fixture
    status, resp, _ = api(
        "POST",
        "/api/scanner/capture",
        is_multipart=(
            str(FIXTURES / "pan_en_DEMON0123F.png"),
            {
                "session_id": session_id,
                "service_id": "acc-001",
                "document_id": "doc-pan",
            },
        ),
    )
    report("Capture endpoint processes PAN", status == 200 and resp.get("scan_id"), resp)
    if status != 200:
        return session_id
    scan_id = resp["scan_id"]
    report("Capture returns classification", resp["result"]["classification"]["match"] == "MATCH")
    report("Capture returns extraction status", resp["result"]["extraction_status"] in ("SUCCESS", "PARTIAL"))
    report("Scan status is confirmation_pending", resp["status"] == "confirmation_pending", resp["status"])

    # 2. result endpoint
    status, res2, _ = api("GET", f"/api/scanner/result/{scan_id}")
    report("Result endpoint returns stored scan", status == 200 and res2["scan_id"] == scan_id)
    report("Result does NOT leak raw OCR text", "text" not in (res2.get("result") or {}))

    # 3. processed image preview
    status, _, raw = api("GET", f"/api/scanner/image/{scan_id}")
    report("Processed preview image served", status == 200 and raw and raw[:2] == b"\xff\xd8")

    # 4. confirm endpoint (customer confirmation required before checklist READABLE)
    status, conf, _ = api("POST", f"/api/scanner/confirm/{scan_id}", body={"corrections": {"full_name": "Customer Corrected Name"}})
    report("Confirm endpoint applies customer correction",
           status == 200 and conf["result"]["fields"]["full_name"]["source"] == "customer", conf)
    report("Confirmed status recorded", conf["status"] == "confirmed")

    # checklist should now show readable for doc-pan (application overlay)
    status, chk, _ = api("GET", f"/api/documents/service/acc-001/checklist?application_id={session_id}")
    pan_item = next((d for d in chk["documents"] if d["document_id"] == "doc-pan"), None)
    report("Checklist doc-pan updated to readable", pan_item and pan_item["status"] == "readable",
           pan_item and pan_item["status"])

    # 5. rescan endpoint
    status, rescan, _ = api("POST", f"/api/scanner/rescan/{scan_id}")
    report("Rescan sets needs_rescan", status == 200 and rescan["status"] == "needs_rescan")

    # 6. upload endpoint (device upload semantics) with aadhaar to acc-001
    status, up, _ = api(
        "POST",
        "/api/scanner/upload",
        is_multipart=(
            str(FIXTURES / "aadhaar_en_2345_1234_5678.png"),
            {"session_id": session_id, "service_id": "acc-001", "document_id": "doc-aadhaar"},
        ),
    )
    report("Upload endpoint processes Aadhaar", status == 200 and up.get("scan_id"), up)

    # 7. status per session
    status, st, _ = api("GET", f"/api/scanner/status/{session_id}")
    report("Session status shows 2 scans", status == 200 and len(st.get("services", {})) > 0)

    # 8. mismatched relationships must be rejected (gst fixture is not part of
    #    the savings-account checklist, so the association itself is invalid)
    status, _, _ = api(
        "POST",
        "/api/scanner/upload",
        is_multipart=(
            str(FIXTURES / "gst_registration.png"),
            {"session_id": session_id, "service_id": "acc-001", "document_id": "doc-fee-structure"},
        ),
    )
    report("Fee structure upload for savings account rejected", status in (400, 422), status)

    # 9. wrong file type rejected
    import tempfile
    txt = tempfile.NamedTemporaryFile(suffix=".txt", delete=False)
    txt.write(b"not an image")
    txt.close()
    status, _, _ = api(
        "POST",
        "/api/scanner/upload",
        is_multipart=(txt.name, {"session_id": session_id, "service_id": "acc-001", "document_id": "doc-pan"}),
    )
    report("Non-image file rejected with 415", status == 415, status)
    Path(txt.name).unlink(missing_ok=True)

    # 10. cleanup endpoint removes temp files for the session
    status, cl, _ = api("POST", f"/api/scanner/cleanup/{session_id}")
    report("Cleanup endpoint reports removed scans", status == 200, cl)
    temp_dir = BACKEND / "temp_scans" / session_id
    report("Temp folder removed after cleanup", not temp_dir.exists(), str(temp_dir))

    # delete session
    api("DELETE", f"/api/session/{session_id}")
    return session_id


def main():
    print_safe("PHASE 4 TEST RUN - synthetic fixtures only")
    run_service_tests()
    run_api_tests()
    print_safe("")
    total = RESULTS["pass"] + RESULTS["fail"]
    print_safe(f"RESULTS: {RESULTS['pass']}/{total} passed, {RESULTS['fail']} failed")
    if RESULTS["failures"]:
        print_safe("Failed tests:")
        for f in RESULTS["failures"]:
            print_safe("  - " + f)
    return RESULTS["fail"] == 0


if __name__ == "__main__":
    ok = main()
    sys.exit(0 if ok else 1)
