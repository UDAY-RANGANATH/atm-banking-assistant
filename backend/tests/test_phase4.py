"""
Phase 4 automated test suite - Camera Scanner and Intelligent OCR Engine.

Verification approach: this script can run in two modes.
  1. SERVICE mode  - direct service-layer tests (no server required)
  2. API mode      - HTTP tests against a running server (default port 8000)

Fixtures are SYNTHETIC documents generated by scripts/generate_test_docs.py.
No real identity documents are used anywhere in testing.

Print-safe on cp1252 consoles (ascii fallback for non-latin output).
"""

import sys
import json
import time
import shutil
import subprocess
import urllib.request
import urllib.error
from pathlib import Path

BACKEND = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(BACKEND))

FIXTURES = BACKEND / "tests" / "fixtures"
RESULTS = {"pass": 0, "fail": 0, "failures": []}


def report(name, ok, detail=""):
    if ok:
        RESULTS["pass"] += 1
        print_safe("PASS: " + name)
    else:
        RESULTS["fail"] += 1
        RESULTS["failures"].append(name)
        print_safe("FAIL: " + name + (" - " + str(detail) if detail else ""))


def print_safe(s):
    try:
        print(s)
    except Exception:
        print(s.encode("ascii", errors="replace").decode())


def api(method, path, body=None, is_multipart=None, base="http://127.0.0.1:8000"):
    """HTTP helper. Returns (status, parsed_json_or_None, raw_bytes_or_None)."""
    url = base + path
    data = None
    headers = {}
    if is_multipart:
        with open(is_multipart[0], "rb") as fh:
            file_bytes = fh.read()
        boundary = "----protoBoundaryPhase4"
        filename = Path(is_multipart[0]).name
        ctype = {
            ".png": "image/png",
            ".jpg": "image/jpeg",
            ".jpeg": "image/jpeg",
            ".webp": "image/webp",
            ".bmp": "image/bmp",
        }.get(Path(is_multipart[0]).suffix.lower(), "application/octet-stream")
        parts = []
        for k, v in is_multipart[1].items():
            parts.append(
                f'--{boundary}\r\nContent-Disposition: form-data; name="{k}"\r\n\r\n{v}\r\n'
            )
        parts.append(
            f'--{boundary}\r\nContent-Disposition: form-data; name="file"; filename="{filename}"\r\n'
            f"Content-Type: {ctype}\r\n\r\n"
        )
        payload = "".join(parts).encode("utf-8") + file_bytes + f"\r\n--{boundary}--\r\n".encode()
        data, headers = payload, {"Content-Type": f"multipart/form-data; boundary={boundary}"}
    elif body is not None:
        data, headers = json.dumps(body).encode(), {"Content-Type": "application/json"}
    req = urllib.request.Request(url, data=data, headers=headers, method=method)
    try:
        resp = urllib.request.urlopen(req, timeout=120)
        raw = resp.read()
        try:
            return resp.status, json.loads(raw.decode()), raw
        except Exception:
            return resp.status, None, raw
    except urllib.error.HTTPError as e:
        raw = e.read()
        try:
            return e.code, json.loads(raw.decode()), raw
        except Exception:
            return e.code, None, raw


