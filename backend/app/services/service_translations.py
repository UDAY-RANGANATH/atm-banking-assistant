_TIME_UNIT_TE = "నిమిషాలు"
_TIME_UNIT_HI = "मिनट"
_TIME_UNITS = {"te": _TIME_UNIT_TE, "hi": _TIME_UNIT_HI}


def category_labels(category_key: str) -> Dict[str, str]:
    """Localized labels for a category key, e.g. {"te": "...", "hi": "..."}."""
    return CATEGORY_LABEL_TRANSLATIONS.get(category_key, {})


def localized_service_fields(service: Any) -> Dict[str, Dict[str, str]]:
    """
    Localized view-summary fields for one BankingService - the strings the
    kiosk shows on cards and the help summary: name / description /
    eligibility / estimatedTime (time unit localized from the English one).
    Missing translations fall back to None keys (omitted at serialization).
    """
    out: Dict[str, Dict[str, str]] = {}
    for lang_code, fields in SERVICE_TRANSLATIONS.get(getattr(service, "id", ""), {}).items():
        view: Dict[str, str] = {
            "name": fields["name"],
            "description": fields["description"],
            "eligibility": fields.get("eligibility", ""),
        }
        unit = _TIME_UNITS.get(lang_code)
        est_time = getattr(service, "estimatedTime", "") or ""
        if unit and est_time:
            view["estimatedTime"] = est_time.replace("min", unit)
        else:
            view["estimatedTime"] = est_time
        out[lang_code] = view
    return out
